"""The relevance term must separate a construct definition from a mention.

An audit of 40 zero-site genes found seven real published tag sites the pipeline
had missed. Six were lost the same way: the decisive sentence scored exactly
3.0 — tied with every other on-topic sentence in its paper — so the per-section
and per-paper caps cut by POSITION among the ties and the construct definition
lost to narrative. The scoring was effectively binary; these pin the gradient
that fixes it.

Every VERBATIM string below is the real sentence from the real paper, with the
rank it was cut at, so a future change that re-flattens the scoring fails here
rather than silently costing sites again.
"""
from __future__ import annotations

import pytest

from accessible_surfaceome.agents.tag_site.runner import tag_site_relevance

#: Any sequence works for the non-residue signals; residue_mentions is the one
#: term that needs the real thing and is already covered elsewhere.
SEQ = "MLLLLLLLLLAHSEAKKGSKFDTPPPPPPPP"

#: The sentence class that used to win the tie: on-topic, names the construct,
#: pins nothing.
GENERIC = (
    "IB analysis of the anti-HA IPs derived from the H1299 and 293T cells "
    "transfected with the HA-ins-PD-L1 wild type."
)

# (label, sentence, rank it was cut at)
LOST = [
    ("CD274 / PD-L1, cut at rank 233 of 900",
     "In the HA-ins-PD-L1, the HA-tag was inserted into the PD-L1 sequence "
     "after the signal peptide sequence."),
    ("LRRC8E, cut at rank 386 of 819",
     "The sequence of LRRC8E with the HA tag was CLPNHE YPYDVPDYA LQENLS "
     "(HA tag in italics)."),
    ("ADAM17, cut at rank 292 of 774",
     "Expression plasmids of ADAM17 with the HiBiT sequence inserted between "
     "metalloprotease and disintegrin domains"),
    ("IL1RAP, cut by the per-paper cap",
     "Expression vectors for mutated forms were generated by PCR-based "
     "mutagenesis using pEB6-PTPd-ECD-Fc, pFLAG-IL-1RAcPb and pFLAG-IL1RAPL1"),
    ("LSAMP, figure legend, absent from the pool",
     "Surface Myc-IgLON expression was detected with anti-Myc antibody in the "
     "absence of permeabilization."),
]


@pytest.mark.parametrize("label,sentence", LOST, ids=[x[0][:28] for x in LOST])
def test_a_construct_definition_outranks_a_mere_mention(label: str, sentence: str) -> None:
    score = tag_site_relevance(SEQ)
    assert score(sentence) > score(GENERIC), (
        f"{label}: scored {score(sentence)} vs {score(GENERIC)} for a sentence "
        f"that merely mentions the construct — a tie is what let the cap cut it"
    )


def test_background_prose_still_scores_zero() -> None:
    """The gradient must not promote non-probative sentences."""
    score = tag_site_relevance(SEQ)
    assert score(
        "Programmed death-ligand 1 is an immune checkpoint molecule widely "
        "studied in cancer immunotherapy."
    ) == 0.0


def test_a_topology_anchor_counts_without_any_residue() -> None:
    """60% of real sites are topology_derived and name no residue at all, so
    'after the signal peptide' has to be worth something on its own."""
    score = tag_site_relevance(SEQ)
    anchored = "The FLAG tag was placed after the signal peptide of the receptor."
    assert score(anchored) > 3.0
